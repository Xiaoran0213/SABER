#!/usr/bin/env python
"""Materialize and orchestrate the 5-seed SABER full benchmark (sequential chain).

The driver:
  1. Materializes one full benchmark per seed {42, 123, 2024, 2025, 7} into
     ``outputs/paper_benchmark_<date>_5seed/seeds/seed<S>/`` (each carries the
     PLM-ridge/PLM-kNN expansion references and the KNN imputation/LFQ method).
  2. Generates a top-level ``submit_5seed_chain.sh`` that runs the seeds as a
     strict sequential dependency chain (seed_i train -> ext -> seed_{i+1}
     train -> ext -> ... -> multiseed collect), keeping the live job count to
     ~1-2 (well under the stat QoS MaxSubmitPU=100).
  3. Generates a multiseed collect job that merges all 5 per-seed plans into one
     ``source_metrics_long.csv`` and renders the paper figures.

It does NOT submit anything; run ``bash <root>/submit_5seed_chain.sh`` to launch
(after spot-checking with a smoke run).

Usage:
  conda run -n saber python scripts/run_5seed_campaign.py [--epochs 300] [--date YYYYMMDD]
"""

from __future__ import annotations

import argparse
import datetime
import json
from pathlib import Path

import sys as _sys  # noqa: E402
_sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # resolve `saber` from this checkout, not the env
from saber.full_benchmark import materialize_full_benchmark


REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SEEDS = (42, 123, 2024, 2025, 7)


def _q(path: str | Path) -> str:
    return f'"{Path(path)}"'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--seeds", default=",".join(str(s) for s in DEFAULT_SEEDS))
    parser.add_argument("--epochs", type=int, default=300)
    parser.add_argument("--batch-size", type=int, default=32)
    parser.add_argument("--date", default="", help="YYYYMMDD run date (default: today)")
    parser.add_argument("--tag", default="5seed")
    parser.add_argument("--device", default="auto")
    parser.add_argument("--train-partition", default="stat")
    parser.add_argument("--external-partition", default="stat")
    # Robustness arms (0723 plan §1/§2). TURN THESE ON for the final frozen+uniform
    # re-run so the missingness grid + sequence-cluster holdout are produced in the
    # same campaign and flow into source_metrics_long.csv. Off = plain main benchmark.
    parser.add_argument("--missingness-grid", action="store_true",
                        help="add full missing-fraction x MNAR-share imputation grid (supp)")
    parser.add_argument("--sequence-holdout", action="store_true",
                        help="add sequence-cluster (MMseqs2) expansion holdout on human datasets")
    args = parser.parse_args()

    seeds = [int(s) for s in args.seeds.split(",") if s.strip()]
    date = args.date or datetime.datetime.now().strftime("%Y%m%d")
    from saber.paths import outputs_root
    root = outputs_root() / f"paper_benchmark_{date}_{args.tag}"
    root.mkdir(parents=True, exist_ok=True)
    (root / "logs" / "slurm").mkdir(parents=True, exist_ok=True)

    plan_paths: list[str] = []
    for seed in seeds:
        seed_root = root / "seeds" / f"seed{seed}"
        print(f"[5seed] materializing seed={seed} -> {seed_root}", flush=True)
        result = materialize_full_benchmark(
            root=str(seed_root),
            seed=seed,
            epochs=args.epochs,
            batch_size=args.batch_size,
            device=args.device,
            train_partition=args.train_partition,
            external_partition=args.external_partition,
            missingness_grid=args.missingness_grid,
            sequence_holdout=args.sequence_holdout,
        )
        plan_paths.append(str(result.plan_path.resolve()))

    # --- multiseed collect wrapper (evaluates all plans -> one source CSV + figures)
    collect_wrapper = root / "collect_5seed.py"
    plans_block = ",\n    ".join(_q(p) for p in plan_paths)
    collect_wrapper.write_text(
        "#!/usr/bin/env python\n"
        "\"\"\"Generated by run_5seed_campaign.py: evaluate all per-seed plans, merge, plot.\"\"\"\n"
        "from pathlib import Path\n\n"
        "from saber.full_benchmark import collect_full_benchmark_multiseed_source_data\n"
        "from saber.paper_figures import make_paper_figures\n\n"
        "PLANS = [\n"
        f"    {plans_block},\n"
        "]\n"
        "ROOT = Path(__file__).resolve().parent\n"
        "source_dir = ROOT / 'source_data'\n"
        "figures_dir = ROOT / 'paper_figures'\n"
        "res = collect_full_benchmark_multiseed_source_data(PLANS, source_dir)\n"
        "print('merged source_csv:', res['source_csv'])\n"
        "fig = make_paper_figures(res['source_csv'], figures_dir, formats=('png', 'pdf'))\n"
        "print('figures manifest:', fig['manifest'])\n"
        "if fig.get('warnings'):\n"
        "    print('figure warnings:', fig['warnings'])\n",
        encoding="utf-8",
    )
    collect_wrapper.chmod(0o755)

    # --- collect sbatch
    slurm_dir = root / "slurm"
    slurm_dir.mkdir(parents=True, exist_ok=True)
    collect_sbatch = slurm_dir / "collect_multiseed.sbatch"
    collect_sbatch.write_text(
        "#!/usr/bin/env bash\n"
        "#SBATCH --job-name=saber_collect5\n"
        "#SBATCH --partition=stat\n"
        "#SBATCH --cpus-per-task=4\n"
        "#SBATCH --mem=32G\n"
        "#SBATCH --time=12:00:00\n"
        f"#SBATCH --output={root}/logs/slurm/saber_collect5_%j.out\n"
        f"#SBATCH --error={root}/logs/slurm/saber_collect5_%j.err\n"
        "set -euo pipefail\n"
        f"cd {REPO_ROOT}\n"
        f"conda run -n saber python {collect_wrapper}\n",
        encoding="utf-8",
    )
    collect_sbatch.chmod(0o755)

    # --- top-level sequential-chain submit script
    seeds_space = " ".join(str(s) for s in seeds)
    submit = root / "submit_5seed_chain.sh"
    submit.write_text(
        "#!/usr/bin/env bash\n"
        "# Sequential chain across seeds; ~1-2 jobs live at a time (under stat MaxSubmitPU=100).\n"
        "set -euo pipefail\n"
        f'ROOT="{root}"\n'
        f'SEEDS=({seeds_space})\n'
        'prev=""\n'
        'for s in "${SEEDS[@]}"; do\n'
        '  sd="$ROOT/seeds/seed$s"\n'
        '  if [ -z "$prev" ]; then\n'
        '    train=$(sbatch --parsable "$sd/slurm/train_sequential.sbatch")\n'
        '  else\n'
        '    train=$(sbatch --parsable --dependency=afterok:$prev "$sd/slurm/train_sequential.sbatch")\n'
        '  fi\n'
        '  echo "seed $s train_seq: $train"\n'
        '  ext=$(sbatch --parsable --dependency=afterok:$train "$sd/slurm/external_sequential.sbatch")\n'
        '  echo "seed $s ext_seq: $ext"\n'
        '  prev="$ext"\n'
        'done\n'
        'collect=$(sbatch --parsable --dependency=afterok:$prev "$ROOT/slurm/collect_multiseed.sbatch")\n'
        'echo "collect_multiseed: $collect"\n'
        'echo "$collect" > "$ROOT/collect_jobid.txt"\n',
        encoding="utf-8",
    )
    submit.chmod(0o755)

    campaign = {
        "root": str(root),
        "seeds": seeds,
        "epochs": args.epochs,
        "date": date,
        "plans": plan_paths,
        "submit_script": str(submit),
        "collect_sbatch": str(collect_sbatch),
        "collect_wrapper": str(collect_wrapper),
    }
    (root / "campaign_manifest.json").write_text(json.dumps(campaign, indent=2), encoding="utf-8")

    print(f"\n[5seed] DONE. Root: {root}", flush=True)
    print(f"[5seed] Submit (after smoke check): bash {submit}", flush=True)


if __name__ == "__main__":
    main()
